CREATE PROC spAPI_Log_NhanXetThang
@LopID INT,
@Lop_NhanXetThangID INT
as
begin
	DECLARE @Table_Log Table (
		NhanXetThangID				int	,
		Lop_NhanXetThangID			int	,
		HSLopID						int	,
		HocSinhID					int	,
		NoiDungKienThuc_HTML		nvarchar(2000)	,
		NoiDungNangLuc_HTML			nvarchar(2000)	,
		NoiDungHoatDongKhac_HTML	nvarchar(2000)	,
		NoiDungToan_HTML			nvarchar(2000)	,
		NoiDungTiengViet_HTML		nvarchar(2000)	,
		NoiDungMonHocKhac_HTML		nvarchar(2000)	,
		NhanXetCuoiNam_HTML			nvarchar(2000)	,
		DiemToan					int	,
		SoSao_Toan					int	,
		NhanXetToan_HTML			nvarchar(4000)	,
		DiemTiengViet				int	,
		SoSao_TiengViet				int	,
		NhanXetTiengViet_HTML		nvarchar(4000)	,
		NhanXetMonHocKhac_HTML		nvarchar(4000)	,
		HoatDongGiaoDucKhac_HTML	nvarchar(4000)	,
		PhamChatNangLuc_HTML		nvarchar(4000)	,
		Is_Reject					bit	,
		ReasonReject				nvarchar(2000)	,
		Parent_Comment				nvarchar(2000)	,
		Enable						bit	,
		CreateUser					varchar(9)	,
		CreateTime					datetime	,
		UpdateUser					varchar(9)	,
		UpdateTime					datetime	,
		ParentConfirmUser			varchar(9)	,
		ParentConfirmTime			datetime	
	)

	INSERT INTO @Table_Log(
		NhanXetThangID				,
		Lop_NhanXetThangID			,
		HSLopID						,
		HocSinhID					,
		NoiDungKienThuc_HTML		,
		NoiDungNangLuc_HTML			,
		NoiDungHoatDongKhac_HTML	,
		NoiDungToan_HTML			,
		NoiDungTiengViet_HTML		,
		NoiDungMonHocKhac_HTML		,
		NhanXetCuoiNam_HTML			,
		DiemToan					,
		SoSao_Toan					,
		NhanXetToan_HTML			,
		DiemTiengViet				,
		SoSao_TiengViet				,
		NhanXetTiengViet_HTML		,
		NhanXetMonHocKhac_HTML		,
		HoatDongGiaoDucKhac_HTML	,
		PhamChatNangLuc_HTML		,
		Is_Reject					,
		ReasonReject				,
		Parent_Comment				,
		Enable						,
		CreateUser					,
		CreateTime					,
		UpdateUser					,
		UpdateTime					,
		ParentConfirmUser			,
		ParentConfirmTime			
	)
	select 
		NhanXetThangID				,
		Lop_NhanXetThangID			,
		HSLopID						,
		HocSinhID					,
		NoiDungKienThuc_HTML		,
		NoiDungNangLuc_HTML			,
		NoiDungHoatDongKhac_HTML	,
		NoiDungToan_HTML			,
		NoiDungTiengViet_HTML		,
		NoiDungMonHocKhac_HTML		,
		NhanXetCuoiNam_HTML			,
		DiemToan					,
		SoSao_Toan					,
		NhanXetToan_HTML			,
		DiemTiengViet				,
		SoSao_TiengViet				,
		NhanXetTiengViet_HTML		,
		NhanXetMonHocKhac_HTML		,
		HoatDongGiaoDucKhac_HTML	,
		PhamChatNangLuc_HTML		,
		Is_Reject					,
		ReasonReject				,
		Parent_Comment				,
		Enable						,
		CreateUser					,
		CreateTime					,
		UpdateUser					,
		UpdateTime					,
		ParentConfirmUser			,
		ParentConfirmTime			
	from tblNhanXetThang
	UNION
	select 
		NhanXetThangID				,
		Lop_NhanXetThangID			,
		HSLopID						,
		HocSinhID					,
		NoiDungKienThuc_HTML		,
		NoiDungNangLuc_HTML			,
		NoiDungHoatDongKhac_HTML	,
		NoiDungToan_HTML			,
		NoiDungTiengViet_HTML		,
		NoiDungMonHocKhac_HTML		,
		NhanXetCuoiNam_HTML			,
		DiemToan					,
		SoSao_Toan					,
		NhanXetToan_HTML			,
		DiemTiengViet				,
		SoSao_TiengViet				,
		NhanXetTiengViet_HTML		,
		NhanXetMonHocKhac_HTML		,
		HoatDongGiaoDucKhac_HTML	,
		PhamChatNangLuc_HTML		,
		Is_Reject					,
		ReasonReject				,
		Parent_Comment				,
		Enable						,
		CreateUser					,
		CreateTime					,
		UpdateUser					,
		UpdateTime					,
		ParentConfirmUser			,
		ParentConfirmTime			
	from tbl_LOG_NhanXetThang


	SELECT 
		hs.HocSinhID,
		Ho,
		Ten,
		Ho + ' ' + Ten as HoTen,
		NgaySinh,
		NhanXetThangID				,
		Lop_NhanXetThangID			,
		NXT.HSLopID						,
		NoiDungKienThuc_HTML		,
		NoiDungNangLuc_HTML			,
		NoiDungHoatDongKhac_HTML	,
		NoiDungToan_HTML			,
		NoiDungTiengViet_HTML		,
		NoiDungMonHocKhac_HTML		,
		NhanXetCuoiNam_HTML			,
		DiemToan					,
		SoSao_Toan					,
		NhanXetToan_HTML			,
		DiemTiengViet				,
		SoSao_TiengViet				,
		NhanXetTiengViet_HTML		,
		NhanXetMonHocKhac_HTML		,
		HoatDongGiaoDucKhac_HTML	,
		PhamChatNangLuc_HTML		,
		nxt.CreateTime	,
		nxt.CreateUser,
		nxt.UpdateTime,
		nxt.UpdateUser
	FROM @Table_Log nxt
		inner join tblHocSinhLop hsl on nxt.HSLopID = hsl.HSLopID and LopID = @LopID
		inner join tblHocSinh hs on hs.HocSinhID  = hsl.HocSinhID
	where Lop_NhanXetThangID = @Lop_NhanXetThangID
END
